// ---------------------------------------------------------------------------
// "Is this a markdown file?" — the one place that answers it.
//
// The question is asked from a *tree row*, before any read has happened, and a
// tree entry carries only `{ name, path, dir, size, mtime }` — no language. So
// the answer cannot come from an open record (`record.language === 'markdown'`
// only describes a file already in the strip) and it cannot come from
// `lib/file-icons.js`, which maps names to Nerd Font code points and answers
// `readme`/`changelog` by *stem* — a different question, on a table generated by
// `tools/nerd_icons.py` that must never be hand-edited.
//
// The rule mirrors `LANGUAGE_BY_EXTENSION['.md'] === 'markdown'` in
// `src/core/editorfs/files.py`, i.e. the table the *server* uses to name the
// buffer's Monaco language:
//
//   * `.md` only, case-insensitive — a second extension (`.markdown`, `.mdx`)
//     means editing that server table too, and until then agreeing with the
//     server is the point: the menu must never promise a preview for a file the
//     pane calls `plaintext`;
//   * a dotfile has no extension — mirroring `language_for()`'s own guard (the
//     separator at index `0` is part of the name), so a file literally named
//     `.md` is not previewable;
//   * uppercase is fine: `README.MD` is previewable, and the server calls it
//     `markdown` for the same reason (it lowercases).
//
// Out of scope here, and known: a preview renders no relative *images* and
// navigates away on a relative *link*. `renderMarkdown` rewrites no `src`/`href`
// and the app has no byte-serving route (`GET /api/fs/file` is text-only and
// capped), so `<img src="diagram.png">` resolves against the app origin and
// renders a silently broken image; a relative `<a href="other.md">` leaves the
// SPA. Fixing either needs a new asset route gated by the same workspace policy
// (images) or an anchor interceptor inside the preview container (links) —
// never a global DOMPurify hook in `lib/markdown.js`, which the chat shares.
// ---------------------------------------------------------------------------

export function isMarkdownPath(path) {
  if (typeof path !== 'string' || !path) return false
  // The extension is a property of the *name*: the server hands `language_for()`
  // a file name, so `dir/.md` is a dotfile there and must read as one here too.
  const separator = path.lastIndexOf('/')
  const name = separator === -1 ? path : path.slice(separator + 1)
  const index = name.lastIndexOf('.')
  // -1 is a name with no dot (`md`), 0 is a dotfile (`.md`) — neither has an
  // extension to key on, exactly as the server's `language_for()` reads them.
  if (index <= 0) return false
  return name.slice(index).toLowerCase() === '.md'
}
