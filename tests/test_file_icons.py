"""The tree's icon mapping and the font that draws it must not drift apart.

`web/src/lib/file-icons.js`, the two `nerd-icons-*.woff2` subsets and the
`unicode-range` of the "JetBrains Mono Nerd Icons" faces are one unit: a code
point the mapping emits but no face carries renders a tofu box in the tree, and
a code point a face carries but no mapping uses is dead weight shipped to every
browser. All three are generated by ``tools/nerd_icons.py``; these tests hold the
committed artifacts to that contract.

They are hermetic: the code-point comparison reads the JS escapes and the CSS
ranges with the standard library only (``fontTools`` is not a test dependency).
The one check that would need the untracked ``fonts/`` download — re-rendering
the module and reading the woff2 cmaps — is skipped when it is not on the
machine, exactly as ``nerd_icons.check`` degrades.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent


def _load_tool():
    """Import tools/nerd_icons.py (it lives outside the package, like a script)."""
    path = ROOT / "tools/nerd_icons.py"
    spec = importlib.util.spec_from_file_location("nerd_icons", path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["nerd_icons"] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def tool():
    return _load_tool()


def test_declared_code_points_are_pua(tool) -> None:
    """Every glyph the mapping emits is a private-use code point.

    A stray non-PUA escape would mean a real character sneaking into the tree's
    icon column, where no Nerd face would be expected to supply it.
    """
    declared = tool.js_code_points(tool.JS_PATH.read_text(encoding="utf-8"))
    assert declared, "the mapping declares no glyphs"
    outside = [f"U+{c:04X}" for c in declared if not 0xE000 <= c <= 0xF8FF]
    assert not outside, f"non-PUA code points in the mapping: {outside}"


def test_font_faces_cover_exactly_the_declared_code_points(tool) -> None:
    """The CSS ranges of both faces equal the set the module emits — no gap,
    nothing unused."""
    declared = tool.js_code_points(tool.JS_PATH.read_text(encoding="utf-8"))
    blocks = tool.css_blocks(tool.CSS_PATH.read_text(encoding="utf-8"))
    assert len(blocks) == len(tool.SUBSET_WOFF2), (
        f"expected {len(tool.SUBSET_WOFF2)} faces for the family, found {len(blocks)}"
    )
    for block in blocks:
        claimed = tool.expand(block)
        missing = declared - claimed
        extra = claimed - declared
        assert not missing, f"@font-face lacks {sorted(f'U+{c:04X}' for c in missing)}"
        assert not extra, f"@font-face carries unused {sorted(f'U+{c:04X}' for c in extra)}"


def test_subsets_match_the_mapping_when_source_fonts_present(tool) -> None:
    """With the untracked ``fonts/`` download available, the woff2 cmaps and the
    generated module match the tool's tables exactly. Skipped elsewhere."""
    if not tool.source_ttf().exists():
        pytest.skip("fonts/JetBrainsMono source faces are not on this machine")
    pytest.importorskip("fontTools")
    assert tool.check() == 0

